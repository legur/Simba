class StopTest(Exception):
    pass

def get_json(url, headers=None):
    req = Request(url, headers=headers or {"Accept": "application/json"}, method="GET")
    with urlopen(req, timeout=30) as response:
        return json.load(response)

def post_json(url, data, headers):
    req = Request(url, data=json.dumps(data, ensure_ascii=False).encode("utf-8"),
                  headers={"Content-Type":"application/json", **headers}, method="POST")
    # Never retry generation: ambiguous network outcomes may be billable.
    with urlopen(req, timeout=140) as response:
        return json.load(response)

def git_token():
    token = os.environ.get("GH_TOKEN", "")
    if not token:
        raise StopTest("GitHub token unavailable")
    return {"Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28"}

def issue_url():
    number = int(os.environ.get("ISSUE_NUMBER", "0"))
    if not 1 <= number <= 999999:
        raise StopTest("Missing issue number")
    if os.environ.get("GITHUB_REPOSITORY") != REPO:
        raise StopTest("Unexpected repository")
    return f"https://api.github.com/repos/{REPO}/issues/{number}/comments"

def comment_lines():
    result = get_json(issue_url() + "?per_page=100", git_token())
    return [str(row.get("body", "")) for row in result if isinstance(row, dict)]

def post_comment(message):
    post_json(issue_url(), {"body":message}, git_token())

def claim_once(key):
    marker = "TTS-ONCE-CLAIM:" + key
    if any(marker in line for line in comment_lines()):
        raise StopTest(f"Claim already exists for {key}. Refusing a second generation.")
    post_comment(marker + "\nAttempt marked before billable call. No automatic retries.")
    return marker

def make_drive():
    needed = ("GDRIVE_OAUTH_CLIENT_ID", "GDRIVE_OAUTH_CLIENT_SECRET",
              "GDRIVE_OAUTH_REFRESH_TOKEN")
    if any(not os.environ.get(name) for name in needed):
        raise StopTest("Google Drive OAuth secrets unavailable; no synthesis attempted")
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request as GoogleRequest
    from googleapiclient.discovery import build
    creds = Credentials(token=None,
        refresh_token=os.environ["GDRIVE_OAUTH_REFRESH_TOKEN"],
        token_uri="https://oauth2.googleapis.com/token",
        client_id=os.environ["GDRIVE_OAUTH_CLIENT_ID"],
        client_secret=os.environ["GDRIVE_OAUTH_CLIENT_SECRET"],
        scopes=["https://www.googleapis.com/auth/drive"])
    creds.refresh(GoogleRequest())
    drive = build("drive", "v3", credentials=creds, cache_discovery=False)
    q = "name = '" + FOLDER + "' and mimeType = 'application/vnd.google-apps.folder' and 'root' in parents and trashed = false"
    existing = drive.files().list(q=q, fields="files(id,name,shared),nextPageToken",pageSize=20).execute()
    if existing.get("nextPageToken") or len(existing.get("files", [])) > 1:
        raise StopTest("Drive folder selection ambiguous")
    if existing.get("files"):
        folder = existing["files"][0]
    else:
        folder = drive.files().create(
            body={"name":FOLDER,"mimeType":"application/vnd.google-apps.folder"},
            fields="id,name,shared").execute()
    if folder.get("shared"):
        raise StopTest("Refusing to save audio in shared folder")
    return drive, folder["id"]

def assert_wav(blob):
    if not isinstance(blob, bytes) or not 4096 <= len(blob) <= MAX_AUDIO_BYTES:
        raise StopTest("Generated audio size invalid")
    if blob[:4] != b"RIFF" or blob[8:12] != b"WAVE":
        raise StopTest("Generated bytes are not a WAV file")
    with tempfile.TemporaryFile() as f:
        f.write(blob); f.seek(0)
        with wave.open(f,"rb") as wav:
            seconds=wav.getnframes()/wav.getframerate()
            if wav.getnchannels() not in (1,2) or not 2 <= seconds <= 120:
                raise StopTest("WAV stream out of expected range")
            return seconds

def save_drive(drive, folder_id, filename, blob, provider, voice, duration):
    from googleapiclient.http import MediaIoBaseUpload
    import io
    if not re.fullmatch(r"[A-Za-z0-9_.-]+\.wav", filename):
        raise StopTest("Invalid output name")
    query = "name = '" + filename + "' and '" + folder_id + "' in parents and trashed = false"
    exists = drive.files().list(q=query,fields="files(id),nextPageToken").execute()
    if exists.get("nextPageToken") or exists.get("files"):
        raise StopTest("Output filename exists; never overwrite test audio")
    upload = MediaIoBaseUpload(io.BytesIO(blob),mimetype="audio/wav",resumable=True)
    obj = drive.files().create(body={"name":filename,"mimeType":"audio/wav",
        "parents":[folder_id],"description":"PRAGUE-STORY-01 | "+provider+" | "+voice,
        "appProperties":{"simba_benchmark":"PRAGUE-STORY-01","tts_voice":voice,
                         "sha256":hashlib.sha256(blob).hexdigest()}},
        media_body=upload,fields="id,name,size,md5Checksum,parents,shared").execute()
    verify = drive.files().get(fileId=obj["id"],fields="id,name,size,md5Checksum,parents,shared").execute()
    expected_md5 = hashlib.md5(blob,usedforsecurity=False).hexdigest()
    if verify.get("shared") or folder_id not in verify.get("parents",[]) or \
       int(verify.get("size",0)) != len(blob) or verify.get("md5Checksum") != expected_md5:
        raise StopTest("Drive upload read-back verification FAILED")
    return {"file":filename,"provider":provider,"voice":voice,
            "duration_s":round(duration,2),"verified":True}

def gemini_sample(text, voice):
    key = os.environ.get("GEMINI_API_KEY","")
    if not key:
        raise StopTest("Gemini API secret missing")
    data = {
        "model":"gemini-3.8-flash-tts",
        "input":[{"type":"user_input","content":[{"type":"text","text":text,
            "annotations":[{"type":"speech_metadata","style":
                "Warm, restrained, cinematic Russian travel narration. Calm adult male storyteller, thoughtful and intimate. Begin softly, gently build anticipation. Say dates and the price clearly, avoid advertising hype."}]}]}],
        "response_format":{"type":"audio"},
        "generation_config":{"speech_config":[{"voice":voice}]},
    }
    result=post_json(GEMINI_URL,data,{"x-goog-api-key":key})
    # Raw Interactions REST responses place the WAV in steps[].content[].data;
    # result.output_audio is an SDK convenience property, not a REST field.
    payloads=[]
    if isinstance(result,dict):
        audio=result.get("output_audio")
        if isinstance(audio,dict) and isinstance(audio.get("data"),str):
            payloads.append(audio["data"])
        for step in result.get("steps",[]):
            if not isinstance(step,dict) or step.get("type")!="model_output":
                continue
            for part in step.get("content",[]):
                if isinstance(part,dict) and part.get("type")=="audio" and isinstance(part.get("data"),str):
                    payloads.append(part["data"])
    if not payloads:
        raise StopTest("Gemini REST response contained no audio parts; never blindly retry.")
    blob=base64.b64decode(payloads[-1],validate=True)
    duration=assert_wav(blob)
    return blob,duration

def voice_records(value):
    if isinstance(value,list):
        for x in value:
            yield from voice_records(x)
    elif isinstance(value,dict):
        if "ttsRate" in value:
            yield value
        else:
            for x in value.values():
                if isinstance(x,(list,dict)):
                    yield from voice_records(x)

def safe_audio_url(url):
    if not isinstance(url,str):
        raise StopTest("A2E returned no URL")
    p=urlsplit(url)
    if p.scheme!="https" or not p.hostname or p.username or p.password or p.port not in (None,443):
        raise StopTest("Unsafe A2E preview URL")
    host=p.hostname.lower()
    if host in ("localhost",) or host.endswith(".local"):
        raise StopTest("Local A2E preview URL")
    try:
        ip=ipaddress.ip_address(host)
        if not ip.is_global: raise StopTest("Private A2E preview IP")
    except ValueError:
        pass
    return url

def a2e_sample(text, voice_id, expected_rate):
    key=os.environ.get("A2E_API_KEY","")
    if not key:
        raise StopTest("A2E API secret missing")
    headers={"Authorization":"Bearer "+key, "Accept":"application/json"}
    data=get_json(A2E_VOICES_URL,headers)
    matches=[r for r in voice_records(data) if str(r.get("tts_id") or r.get("ttsId") or r.get("value"))==voice_id]
    if len(matches)!=1 or float(matches[0].get("ttsRate",-1))!=expected_rate:
        raise StopTest("Current A2E voice not found or rate changed: no paid synthesis")
    result=post_json(A2E_SYNTH_URL,{"msg":text,"tts_id":voice_id,
        "country":"ru","region":"RU","speechRate":0.95},headers)
    if not isinstance(result,dict) or result.get("code") != 0:
        raise StopTest("A2E did not return success (no retry)")
    url=safe_audio_url(result.get("data"))
    req=Request(url,headers={"Accept":"audio/*,application/octet-stream"})
    with urlopen(req,timeout=80) as r:
        blob=r.read(MAX_AUDIO_BYTES+1)
    if not 2000 <= len(blob) <= MAX_AUDIO_BYTES:
        raise StopTest("A2E preview audio bytes invalid")
    with tempfile.TemporaryDirectory() as td:
        file=Path(td)/"source.audio";file.write_bytes(blob)
        target=Path(td)/"converted.wav"
        p=subprocess.run(["ffmpeg","-nostdin","-hide_banner","-loglevel","error","-y","-i",
            str(file),"-ar","24000","-ac","1","-sample_fmt","s16",str(target)],
            capture_output=True,text=True,timeout=40)
        if p.returncode!=0 or not target.exists():
            raise StopTest("A2E audio conversion failed. No retry.")
        wavbytes=target.read_bytes()
    duration=assert_wav(wavbytes)
    return wavbytes,duration

def main():
    config=json.loads(CONFIG.read_text(encoding="utf-8"))
    text=config["text"]
    if not 100 <= len(text) <= 280 or config["voice_gender"]!="male_only":
        raise StopTest("Benchmark input validation failed")
    drive,folder_id=make_drive()  # Must work BEFORE any billable call
    results=[]
    plan=[("Gemini","Algieba"),("Gemini","Charon"),("A2E","DmitryNeural")]
    for provider,voice in plan:
        key=f"PRAGUE-STORY-01-{provider}-{voice}-20261107"
        try:
            claim_once(key)
            if provider=="Gemini":
                data,dur=gemini_sample(text,voice)
            else:
                data,dur=a2e_sample(text,"63a549c1ad2a27fe43d966d2",1)
            file=f"PRAGUE-STORY-01_{provider}_{voice}.wav"
            stored=save_drive(drive,folder_id,file,data,provider,voice,dur)
            results.append(stored)
            post_comment(f"TTS-SAVED: {key}\nPrivate Google Drive WAV verified. Voice {voice}, duration {dur:.1f} s. No public audio link.")
        except Exception as ex:
            # Do not expose tokens, URL responses, raw output, or personal data in public issue.
            msg=str(ex) if isinstance(ex,StopTest) else type(ex).__name__
            post_comment(f"TTS-FAILED: {key}\n{msg[:240]}. No automatic retry. Inspect billing and private Drive before any new attempt.")
            results.append({"provider":provider,"voice":voice,"verified":False,"error":msg[:120]})
    print(json.dumps({"samples":[{"voice":x["voice"],"provider":x["provider"],
          "verified":x["verified"]} for x in results],
          "note":"No public GitHub audio artifacts created."},ensure_ascii=False))
    if not any(x["verified"] for x in results):
        raise StopTest("No samples were verified")

if __name__=="__main__":
    try:
        main()
    except Exception as exc:
        print("TTS test stopped: "+(str(exc)[:160] if isinstance(exc,StopTest) else type(exc).__name__))
