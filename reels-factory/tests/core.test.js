import test from 'node:test';
import assert from 'node:assert/strict';
import {validateOffer,generateHooks,createStoryboard} from '../src/core.js';
const offer={title:'Неделя в Италии',destination:'Италия',cta:'Напишите нам'};
test('five distinct hooks',()=>{const hooks=generateHooks(offer);assert.equal(hooks.length,5);assert.equal(new Set(hooks).size,5)});
test('storyboard 14 seconds',()=>assert.equal(createStoryboard(offer).scenes.reduce((s,x)=>s+x.seconds,0),14));
test('unverified price blocked',()=>assert.throws(()=>validateOffer({...offer,price:'€999'}),/UNVERIFIED PRICE/));
test('unverified date blocked',()=>assert.throws(()=>validateOffer({...offer,date:'10.10'}),/UNVERIFIED DATE/));
test('conflict blocked',()=>assert.throws(()=>validateOffer({...offer,conflict:true}),/FACT CONFLICT/));
test('hook index validation',()=>assert.throws(()=>createStoryboard(offer,5),/Hook index/));
test('verified facts preserved',()=>{const s=createStoryboard({...offer,price:'€999',priceVerified:true,date:'10 ноября',dateVerified:true});assert.match(s.scenes[1].text,/€999/);assert.match(s.scenes[1].text,/ноября/)});
test('custom hooks',()=>assert.equal(createStoryboard(offer,2,['a','b','c','d','e']).scenes[0].text,'c'));
